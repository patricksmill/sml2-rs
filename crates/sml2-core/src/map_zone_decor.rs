/// A zone screen's decor slot: `(x, y, id)` in OAM space, `$FF` = empty. The
/// expander reads sixteen of these from `sMapSprite0Page` (`$A6B5`).
pub type ZoneSlot = (u8, u8, u8);

/// `$3E277` + bank 24 `$509B`: expand a zone screen's slots into OAM cells.
///
/// Cells come out in slot order, which is the order `$3E277` writes them from
/// `sMapDecorOAMIndex = 4`. Ids at or beyond the table's 188 entries are skipped
/// rather than read past it (the console would follow whatever the neighbouring
/// bytes happen to look like).
pub fn zone_decor_oam(slots: &[ZoneSlot]) -> Vec<(u8, u8, u8, u8)> {
    let mut out = Vec::new();
    for &(x, y, id) in slots {
        if id == 0xFF || id as usize >= ZONE_DECOR_METASPRITES.len() {
            continue;
        }
        for &(dy, dx, tile, attr) in ZONE_DECOR_METASPRITES[id as usize] {
            // `$3E277` reserves entries 0-3 for the cursor; `$6109B`
            // stops at hardware OAM entry 40, even in the middle of a sprite.
            if out.len() == 36 {
                return out;
            }
            out.push((
                y.wrapping_add(dy as u8),
                x.wrapping_add(dx as u8),
                tile,
                attr,
            ));
        }
    }
    out
}

